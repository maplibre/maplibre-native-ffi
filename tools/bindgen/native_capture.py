"""Emit the native copies that queue deliveries make.

A queue delivery outlives the call that produced it, so native code copies a
completion's value, or a delivered callback's arguments, into storage that the
delivery owns. Every copy is generated from the record's plan, so it follows
each pointer that the header declares.
"""

from __future__ import annotations

from typing import assert_never

from .compiler import compile_api
from .model import Api, ModelError
from .semantic import BoundApi, ValuePlan

# The copies that the native core makes for queue deliveries.
DELIVERY_CAPTURE = "src/delivery/capture_generated.inc"


def generate(api: Api | BoundApi) -> dict[str, str]:
    """The native copies for queue deliveries."""
    return {DELIVERY_CAPTURE: delivery_capture(compile_api(api))}


def completion_values(bound: BoundApi) -> dict[str, ValuePlan]:
    """The plan of each value type that a completion delivers, by C spelling.

    An array result contributes its element type.
    """
    from .native_results import completion_results

    values = {}
    for result in completion_results(bound):
        if result.type is None:
            continue
        plan = bound.operations_by_name[result.function].result
        assert plan is not None
        if plan.kind == "array":
            assert plan.element is not None
            plan = plan.element
        values.setdefault(result.type, plan)
    return values


def delivery_records(bound: BoundApi):
    """Each callback that a queue delivers, with the plan of its copied record,
    sorted by record name."""
    entries = []
    for callback in bound.callbacks.values():
        if callback.delivery is None:
            continue
        plan = bound.values.get(callback.delivery.record)
        if plan is None:
            raise ModelError(
                [
                    f"{callback.native}: delivery record {callback.delivery.record} is unbound"
                ]
            )
        entries.append((callback, plan))
    return sorted(entries, key=lambda entry: entry[1].native)


def _release_call(handle, value: str) -> str:
    kind = "".join(
        word.title()
        for word in handle.native.removeprefix("mln_")
        .removesuffix("_handle")
        .split("_")
    )
    return f"static_cast<void>(dispose_owner(mln::core::HandleKind::{kind}, {value}));"


def delivery_capture(bound: BoundApi) -> str:
    """The copies that the native core makes for queue deliveries.

    Each completion value type, and each delivered callback's record, gets a
    capture_element() overload, which copies one value into an arena, a
    discard_element() overload, which disposes the handles that a copy owns,
    and an element_owns_handles() overload. The core resolves the overloads by
    type, so a value type without one fails to compile. Each delivered
    callback also gets a Delivered specialization, which names its record,
    callback type, and payload member for its delivery type, and an invoke()
    that passes a copied record to the callback.
    """
    output = ["// Generated by tools/bindgen. Do not edit."]
    for native, plan in sorted(completion_values(bound).items()):
        _validate_capture_ownership(plan)
        output.extend(_element(native, plan, []))
    records = set()
    for callback, plan in delivery_records(bound):
        manual = (
            bound.source.typedefs_by_name[plan.native].metadata.get("capture")
            == "manual"
        )
        if not manual:
            _validate_capture_ownership(plan, delivered=True)
            owned = [
                _release_call(field.value.handle, f"value.{field.name}")
                for field in plan.fields
                if field.value.kind == "handle" and field.value.ownership == "owned"
            ]
            # Callbacks of the same shape share a record and its overloads.
            if plan.native not in records:
                records.add(plan.native)
                output.extend(_element(plan.native, plan, owned))
        output.extend(
            [
                "template <>",
                f"struct Delivered<{callback.delivery.constant}> {{",
                f"  using Record = {plan.native};",
                f"  using Callback = {callback.native};",
                f"  static constexpr auto member = &mln_delivery_payload::{callback.delivery.payload_member};",
                *_invoke(callback, plan),
                "};",
            ]
        )
    output.append("")
    return "\n".join(output)


def _invoke(callback, plan) -> list[str]:
    """The thunk that passes a copied record back to its callback, for a
    dispatched call. The record's fields mirror the callback's parameters
    after its context, so each argument is the field of the same name."""
    fields = {field.name for field in plan.fields}
    arguments = []
    for parameter in callback.parameters:
        if parameter.name == callback.context:
            arguments.append("user_data")
        elif parameter.name in fields:
            arguments.append(f"record.{parameter.name}")
        else:
            raise ModelError(
                [
                    f"{callback.native}: delivery record {plan.native} has no field {parameter.name}"
                ]
            )
    return [
        "  static auto invoke(Callback callback, void* user_data, const Record& record) noexcept -> void {",
        f"    static_cast<void>(callback({', '.join(arguments)}));",
        "  }",
    ]


def _element(native: str, plan, releases: list[str]) -> list[str]:
    """The capture, discard, and ownership overloads of one value type."""
    return [
        "template <bool Writing>",
        f"auto capture_element([[maybe_unused]] Arena<Writing>& arena, const {native}& source) -> {native} {{",
        "  auto result = source;",
        *_capture(plan, "source", "result", "", 1),
        "  return result;",
        "}",
        f"inline auto discard_element([[maybe_unused]] const {native}& value) noexcept -> void {{",
        *(f"  {release}" for release in releases),
        "}",
        f"constexpr auto element_owns_handles(const {native}*) noexcept -> bool {{",
        f"  return {'true' if releases else 'false'};",
        "}",
    ]


def _validate_capture_ownership(plan, *, nested=False, delivered=False):
    """A delivered record may own the handles in its own fields, which its
    discard releases; any deeper owned handle would need recursive disposal."""
    if plan.kind == "handle" and plan.ownership == "owned" and nested:
        raise ModelError(
            [f"{plan.native}: nested owned capture requires recursive disposal"]
        )
    for field in plan.fields:
        if delivered and field.value.kind == "handle":
            continue
        _validate_capture_ownership(field.value, nested=True)
    if plan.element is not None:
        _validate_capture_ownership(plan.element, nested=True)


def _capture(
    plan: ValuePlan, source: str, target: str, parent: str, depth: int
) -> list[str]:
    indent = "  " * depth
    if plan.kind in {"scalar", "enum", "handle"}:
        return []
    if plan.kind == "buffer":
        match plan.buffer_form:
            case "view":
                copy = "byte_buffer" if plan.encoding == "bytes" else "buffer"
                return [f"{indent}{target} = {copy}(arena, {source});"]
            case "pointer":
                if plan.length == "nul":
                    raise ModelError(
                        [f"{plan.native}: copied text must be a buffer view"]
                    )
                if not plan.length:
                    raise ModelError([f"{plan.native}: capture buffer requires length"])
                pointer = (
                    f"static_cast<const std::byte*>({source})"
                    if plan.ctype.pointee and plan.ctype.pointee.kind == "void"
                    else source
                )
                return [
                    f"{indent}{target} = bytes(arena, {pointer}, {parent}.{plan.length});"
                ]
            case None:
                raise ModelError([f"{plan.native}: buffer has no form"])
            case _:
                assert_never(plan.buffer_form)
    if plan.kind == "record":
        lines = []
        for field in plan.fields:
            child = field.value
            selector = field.presence
            child_source, child_target = (
                f"{source}.{field.name}",
                f"{target}.{field.name}",
            )
            if child.kind == "union":
                tag = selector.tag if selector else child.tag
                if not tag:
                    raise ModelError(
                        [f"{plan.native}.{field.name}: capture union requires tag"]
                    )
                lines.append(f"{indent}switch ({source}.{tag}) {{")
                for variant in child.fields:
                    if not variant.presence or not variant.presence.variant:
                        raise ModelError(
                            [
                                f"{plan.native}.{field.name}: capture union requires variants"
                            ]
                        )
                    lines.append(f"{indent}  case {variant.presence.variant}:")
                    lines.extend(
                        _capture(
                            variant.value,
                            f"{child_source}.{variant.name}",
                            f"{child_target}.{variant.name}",
                            child_source,
                            depth + 2,
                        )
                    )
                    lines.append(f"{indent}    break;")
                lines.extend(
                    [
                        f'{indent}  default: throw std::invalid_argument{{"unknown completion variant"}};',
                        f"{indent}}}",
                    ]
                )
            elif selector and selector.mask:
                condition = f"({source}.{selector.mask} & {selector.bit}) != 0"
                lines.append(f"{indent}if ({condition}) {{")
                lines.extend(
                    _capture(child, child_source, child_target, source, depth + 1)
                )
                lines.extend(
                    [
                        f"{indent}}} else {{",
                        f"{indent}  {child_target} = {{}};",
                        f"{indent}}}",
                    ]
                )
            else:
                lines.extend(_capture(child, child_source, child_target, source, depth))
        return lines
    if plan.kind in {"array", "reference"}:
        element = plan.element
        assert element is not None
        length = plan.length if plan.kind == "array" else "1"
        if length is None:
            raise ModelError([f"{plan.native}: capture array requires length"])
        count = str(length) if str(length).isdigit() else f"{parent}.{length}"
        if plan.kind == "reference" and plan.nullable:
            count = f"({source} == nullptr ? 0 : 1)"
        name = f"element_{depth}"
        if plan.ctype.kind == "array":
            lines = [
                f"{indent}for (std::size_t index_{depth} = 0; index_{depth} < {count}; ++index_{depth}) {{"
            ]
            lines.extend(
                _capture(
                    element,
                    f"{source}[index_{depth}]",
                    f"{target}[index_{depth}]",
                    parent,
                    depth + 1,
                )
            )
            lines.append(f"{indent}}}")
            return lines
        if element.kind in {"scalar", "enum", "handle"}:
            return [f"{indent}{target} = bytes(arena, {source}, {count});"]
        lines = [
            f"{indent}{target} = span(arena, {source}, {count}, [&]([[maybe_unused]] auto& arena, auto {name}) {{",
            f"{indent}  auto copied_{depth} = {name};",
        ]
        lines.extend(_capture(element, name, f"copied_{depth}", parent, depth + 1))
        lines.extend([f"{indent}  return copied_{depth};", f"{indent}}});"])
        return lines
    if plan.kind in {"callback", "native_pointer", "union"}:
        raise ModelError(
            [f"{plan.native}: native capture does not support {plan.kind}"]
        )
    assert_never(plan.kind)
