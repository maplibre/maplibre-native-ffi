"""Emit the native copies that queue deliveries make.

A queue delivery outlives the call that produced it, so native code copies a
completion's value, or a delivered callback's arguments, into storage that the
delivery owns. Every copy is generated from the record's plan, so it follows
each pointer that the header declares.
"""

from __future__ import annotations

from .compiler import compile_api
from .model import Api, Function, ModelError
from .schema import has_diagnostic
from .semantic import BoundApi, ValuePlan

# The generated binding-support header, under the include directory. The
# frontend parses it with the others, but nothing that it declares feeds its own
# generation.
HEADER = "maplibre_native_c/binding_support_generated.h"
# The copies that the native core makes for queue deliveries.
DELIVERY_CAPTURE = "src/delivery/capture_generated.inc"


def native_call(function: Function, *arguments: str) -> str:
    """Calls a C function, discarding its diagnostic when it takes one."""
    if has_diagnostic(function):
        arguments = (*arguments, "nullptr")
    return f"{function.name}({', '.join(arguments)})"


def generate(api: Api | BoundApi) -> dict[str, str]:
    """The native copies for queue deliveries and the Dart port callbacks."""
    from . import native_ports

    bound = compile_api(api)
    port_header, port_output = native_ports.generate(bound)
    header = [
        "// Generated by tools/bindgen. Do not edit.",
        "#ifndef MAPLIBRE_NATIVE_C_BINDING_SUPPORT_GENERATED_H",
        "#define MAPLIBRE_NATIVE_C_BINDING_SUPPORT_GENERATED_H",
        "#include <stdint.h>",
        *port_header,
        "#endif",
        "",
    ]
    return {
        "include/" + HEADER: "\n".join(header),
        native_ports.PATH: port_output,
        DELIVERY_CAPTURE: delivery_capture(bound),
    }


def completion_values(bound: BoundApi) -> dict[str, ValuePlan]:
    """The plan of each value type that a completion delivers, by C spelling.

    An array result contributes its element type.
    """
    from .native_results import completion_results

    values = {}
    for result in completion_results(bound):
        if result.type is None:
            continue
        plan = bound.operations_by_name[result.function].result
        assert plan is not None
        if plan.kind == "array":
            assert plan.element is not None
            plan = plan.element
        values.setdefault(result.type, plan)
    return values


def delivery_records(bound: BoundApi):
    """Each callback that a queue delivers, with the plan of its copied record,
    sorted by record name."""
    entries = []
    for callback in bound.callbacks.values():
        if callback.delivery is None:
            continue
        plan = bound.values.get(callback.delivery.record)
        if plan is None:
            raise ModelError(
                [
                    f"{callback.native}: delivery record {callback.delivery.record} is unbound"
                ]
            )
        entries.append((callback, plan))
    return sorted(entries, key=lambda entry: entry[1].native)


def _dispose_owner(bound: BoundApi) -> list[str]:
    source = bound.source
    output = [
        "inline auto dispose_owner(const char* native_type, std::uint64_t handle) noexcept -> mln_status {",
        "  if (native_type == nullptr) return MLN_STATUS_INVALID_ARGUMENT;",
    ]
    for handle in sorted(bound.handles.values(), key=lambda item: item.native):
        if not handle.dispose:
            continue
        operation = source.functions_by_name[handle.dispose]
        call = native_call(operation, f"static_cast<{handle.native}>(handle)")
        body = (
            f"{call}; return MLN_STATUS_OK;"
            if operation.return_type.kind == "void"
            else f"return {call};"
        )
        output.append(
            f'  if (std::strcmp(native_type, "{handle.native}") == 0) {{ {body} }}'
        )
    output.extend(["  return MLN_STATUS_INVALID_ARGUMENT;", "}", ""])
    return output


def _release_call(bound: BoundApi, handle, value: str) -> str:
    function = bound.source.functions_by_name[handle.dispose or handle.release]
    call = native_call(function, value)
    return (
        f"static_cast<void>({call});"
        if function.return_type.kind != "void"
        else f"{call};"
    )


def delivery_capture(bound: BoundApi) -> str:
    """The copies that the native core makes for queue deliveries.

    Each completion value type gets a capture_element() overload, which copies
    one value into an arena, a discard_element() overload, which disposes the
    handles that a copy owns, and an element_owns_handles() overload. Each
    delivered callback's record gets the same pair. The core resolves the
    overloads by type, so a value type without one fails to compile.
    """
    output = ["// Generated by tools/bindgen. Do not edit."]
    for native, plan in sorted(completion_values(bound).items()):
        _validate_capture_ownership(plan)
        owned = plan.kind == "handle" and plan.ownership == "owned"
        if owned:
            assert plan.handle is not None and plan.handle.dispose is not None
        output.extend(
            [
                "template <bool Writing>",
                f"auto capture_element([[maybe_unused]] Arena<Writing>& arena, const {native}& source) -> {native} {{",
                "  auto result = source;",
                *_capture(plan, "source", "result", "", 1),
                "  return result;",
                "}",
                f"inline auto discard_element([[maybe_unused]] const {native}& value) noexcept -> void {{",
                *([f"  {_release_call(bound, plan.handle, 'value')}"] if owned else []),
                "}",
                f"constexpr auto element_owns_handles(const {native}*) noexcept -> bool {{",
                f"  return {'true' if owned else 'false'};",
                "}",
            ]
        )
    for callback, plan in delivery_records(bound):
        _validate_capture_ownership(plan)
        record = plan.native
        decision = callback.decision
        output.extend(
            [
                "template <bool Writing>",
                f"auto capture_{record}([[maybe_unused]] Arena<Writing>& arena, const {record}& source) -> {record} {{",
                "  auto result = source;",
                *_capture(plan, "source", "result", "", 1),
                "  return result;",
                "}",
                "// Releases the handles of a copy that the host did not take.",
                f"inline auto discard_{record}([[maybe_unused]] const {record}& value) noexcept -> void {{",
                *(
                    [
                        f"  {_release_call(bound, decision.handle, f'value.{decision.parameter}')}"
                    ]
                    if decision
                    else []
                ),
                "}",
                f"constexpr auto {record}_owns_handles() noexcept -> bool {{",
                f"  return {'true' if decision else 'false'};",
                "}",
            ]
        )
    output.extend(_dispose_owner(bound))
    return "\n".join(output)


def _validate_capture_ownership(plan, *, nested=False):
    if plan.kind == "handle" and plan.ownership == "owned" and nested:
        raise ModelError(
            [f"{plan.native}: nested owned capture requires recursive disposal"]
        )
    for field in plan.fields:
        _validate_capture_ownership(field.value, nested=True)
    if plan.element is not None:
        _validate_capture_ownership(plan.element, nested=True)


def _capture(plan, source: str, target: str, parent: str, depth: int) -> list[str]:
    indent = "  " * depth
    if plan.kind in {"scalar", "enum", "handle"}:
        if plan.kind == "handle" and plan.ownership == "owned" and parent:
            raise ModelError(
                [f"{plan.native}: nested owned capture requires recursive disposal"]
            )
        return []
    if plan.kind == "buffer":
        if plan.buffer_form == "view":
            return [f"{indent}{target} = buffer(arena, {source});"]
        if plan.length == "nul":
            return [f"{indent}{target} = string(arena, {source});"]
        if plan.length:
            pointer = (
                f"static_cast<const std::byte*>({source})"
                if plan.ctype.pointee and plan.ctype.pointee.kind == "void"
                else source
            )
            return [
                f"{indent}{target} = bytes(arena, {pointer}, {parent}.{plan.length});"
            ]
        raise ModelError([f"{plan.native}: capture buffer requires length"])
    if plan.kind == "record":
        lines = []
        for field in plan.fields:
            child = field.value
            selector = field.presence
            child_source, child_target = (
                f"{source}.{field.name}",
                f"{target}.{field.name}",
            )
            if child.kind == "union":
                tag = selector.tag if selector else child.tag
                if not tag:
                    raise ModelError(
                        [f"{plan.native}.{field.name}: capture union requires tag"]
                    )
                lines.append(f"{indent}switch ({source}.{tag}) {{")
                for variant in child.fields:
                    if not variant.presence or not variant.presence.variant:
                        raise ModelError(
                            [
                                f"{plan.native}.{field.name}: capture union requires variants"
                            ]
                        )
                    lines.append(f"{indent}  case {variant.presence.variant}:")
                    lines.extend(
                        _capture(
                            variant.value,
                            f"{child_source}.{variant.name}",
                            f"{child_target}.{variant.name}",
                            child_source,
                            depth + 2,
                        )
                    )
                    lines.append(f"{indent}    break;")
                lines.extend(
                    [
                        f'{indent}  default: throw std::invalid_argument{{"unknown completion variant"}};',
                        f"{indent}}}",
                    ]
                )
            elif selector and selector.mask:
                condition = f"({source}.{selector.mask} & {selector.bit}) != 0"
                lines.append(f"{indent}if ({condition}) {{")
                lines.extend(
                    _capture(child, child_source, child_target, source, depth + 1)
                )
                lines.extend(
                    [
                        f"{indent}}} else {{",
                        f"{indent}  {child_target} = {{}};",
                        f"{indent}}}",
                    ]
                )
            else:
                lines.extend(_capture(child, child_source, child_target, source, depth))
        return lines
    if plan.kind in {"array", "reference"}:
        length = plan.length if plan.kind == "array" else "1"
        if length is None:
            raise ModelError([f"{plan.native}: capture array requires length"])
        count = str(length) if str(length).isdigit() else f"{parent}.{length}"
        if plan.kind == "reference" and plan.nullable:
            count = f"({source} == nullptr ? 0 : 1)"
        name = f"element_{depth}"
        if plan.ctype.kind == "array":
            lines = [
                f"{indent}for (std::size_t index_{depth} = 0; index_{depth} < {count}; ++index_{depth}) {{"
            ]
            lines.extend(
                _capture(
                    plan.element,
                    f"{source}[index_{depth}]",
                    f"{target}[index_{depth}]",
                    parent,
                    depth + 1,
                )
            )
            lines.append(f"{indent}}}")
            return lines
        if plan.element.kind in {"scalar", "enum", "handle"}:
            return [f"{indent}{target} = bytes(arena, {source}, {count});"]
        lines = [
            f"{indent}{target} = span(arena, {source}, {count}, [&]([[maybe_unused]] auto& arena, auto {name}) {{",
            f"{indent}  auto copied_{depth} = {name};",
        ]
        lines.extend(_capture(plan.element, name, f"copied_{depth}", parent, depth + 1))
        lines.extend([f"{indent}  return copied_{depth};", f"{indent}}});"])
        return lines
    raise ModelError([f"{plan.native}: native capture does not support {plan.kind}"])
