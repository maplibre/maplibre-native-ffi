"""Emit the table of the value each completion function delivers.

The native library delivers a completion value through a type-erased pointer and
count. Every binding reads that pointer as the C type that the function's
`result=` annotation names, so the native core looks the type up in this table
instead of choosing it by hand: a call site that delivers any other type fails
to compile.
"""

from __future__ import annotations

from dataclasses import dataclass

from .compiler import compile_api
from .model import Api
from .semantic import BoundApi

PATH = "src/completion/completion_result_generated.inc"


@dataclass(frozen=True)
class CompletionResultPlan:
    """The value one completion function delivers."""

    function: str
    # The C spelling of one delivered value, or of one element of an array.
    type: str
    # Whether the completion delivers `value_count` values rather than one.
    array: bool
    # Whether a successful completion may deliver no value.
    nullable: bool


def completion_results(api: Api | BoundApi) -> tuple[CompletionResultPlan, ...]:
    """The completion functions that deliver a value, sorted by name."""
    bound = compile_api(api)
    plans = []
    for operation in bound.operations:
        result = operation.result
        if operation.completion is None or result is None:
            continue
        array = result.kind == "array"
        value = result.element if array else result
        assert value is not None
        plans.append(
            CompletionResultPlan(
                operation.name, value.ctype.spelling, array, result.nullable
            )
        )
    return tuple(sorted(plans, key=lambda plan: plan.function))


def generate(api: Api | BoundApi) -> dict[str, str]:
    """Specialize `CompletionResult` for each function that delivers a value."""
    lines = ["// Generated by tools/bindgen. Do not edit."]
    for plan in completion_results(api):
        lines.extend(
            [
                "template <>",
                f"struct CompletionResult<&{plan.function}> {{",
                f"  using type = {plan.type};",
                f"  static constexpr bool array = {str(plan.array).lower()};",
                f"  static constexpr bool nullable = {str(plan.nullable).lower()};",
                "};",
            ]
        )
    lines.append("")
    return {PATH: "\n".join(lines)}
