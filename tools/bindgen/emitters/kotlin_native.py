class NativeShims:
    def __init__(self, bound, functions: dict[str, Function], sites):
        self.bound = bound
        self.abi = Abi(bound.source)
        sites = list(sites)
        # The sites that native calls as function pointers on a threaded
        # target, and those that the page's dispatch calls on Kotlin/Wasm. Only
        # Kotlin/Wasm takes the async forms, and only threaded targets the
        # threaded ones.
        self.sites = [site for site in sites if site.split != "async"]
        self.dispatched = [
            site
            for site in sites
            if site.split != "threaded"
            and (site.form in {"queue", "wake"} or site.name in DISPATCHED_RUNTIME)
        ]
        self.signatures = [self.signature(f) for _, f in sorted(functions.items())]
        self.critical = {
            plan.name
            for plan in (*bound.operations, *bound.runtime_operations)
            if self.critical_native(plan)
        }
        self.layouts = {}

    @staticmethod
    def critical_native(plan):
        # Published snapshots and event drains neither wait for work nor invoke
        # host code. Other immediate calls can wait or release callbacks;
        # submissions can deliver their completion inline, including on rejection.
        # A delivery queue drain can wake its queue again, which runs host code.
        def has_callback(value):
            return (
                value.kind == "callback"
                or value.registration is not None
                or (value.element is not None and has_callback(value.element))
                or any(has_callback(field.value) for field in value.fields)
            )

        return (
            plan.execution in {"snapshot", "event_batch"}
            and not isinstance(plan.support, DeliverySupport)
            and not plan.completion
            and not plan.registrations
            and not any(has_callback(parameter.value) for parameter in plan.inputs)
        )

    def classify(self, ctype):
        if ctype.kind == "void" or ctype.spelling == "void":
            return None
        return self.abi.classify(ctype)

    def signature(self, function: Function) -> Signature:
        parameters = []
        for p in function.parameters:
            kind = self.classify(p.type)
            assert kind is not None
            if isinstance(kind, Array):
                raise LayoutError(f"{function.name}: array parameters have no carrier")
            parameters.append(Parameter(identifier(p.name), p.name, p.type, kind))
        if function.diagnostic:
            parameters.append(
                Parameter(
                    "outDiagnostic", "out_diagnostic", DIAGNOSTIC_POINTER, POINTER
                )
            )
        result = self.classify(function.return_type)
        # C returns no array.
        assert not isinstance(result, Array)
        if isinstance(result, Record):
            parameters.append(
                Parameter(
                    "returned",
                    "returned",
                    CType("pointer", function.return_type.spelling + " *", ""),
                    POINTER,
                    returned=True,
                )
            )
        return Signature(
            function.name,
            tuple(parameters),
            result,
            function.return_type,
            function.metadata.get("blocks"),
        )

    def kotlin_parameters(self, signature):
        return ", ".join(f"{p.name}: {p.carrier}" for p in signature.parameters)

    def common(self):
        lines = [
            f"  fun {s.function}({self.kotlin_parameters(s)}): {s.carrier}"
            for s in self.signatures
        ]
        return (
            HEADER
            + f"package {PACKAGE}\n\n"
            + "/**\n"
            + " * The C functions the binding calls, over primitive carriers: an address or a 64-bit\n"
            + " * integer is a Long, and a record C takes by value crosses as the address of a copy. A record\n"
            + " * C returns by value is written to the trailing `returned` address.\n"
            + " */\n"
            + "internal expect object C {\n"
            + "\n".join(lines)
            + "\n}\n"
        )

    def runtime_layouts(self):
        """Offsets of the records the handwritten completion and status runtime reads."""
        objects = []
        for record, public in (
            (COMPLETION, "CompletionLayout"),
            (COMPLETION_RESULT, "CompletionResultLayout"),
            (DIAGNOSTIC, "DiagnosticLayout"),
            (RENDER_ABANDON_RESULT, "RenderAbandonResultLayout"),
        ):
            if record not in self.bound.source.records_by_name:
                continue
            layouts = tuple(
                self.abi.record_named(record, width, align)
                for width, align in DATA_MODELS
            )
            members = [
                f"  val SIZEOF: Int = {width_expression(tuple(layout.size for layout in layouts))}",
                f"  val ALIGNOF: Int = {width_expression(tuple(layout.align for layout in layouts))}",
            ]
            for field in layouts[0].offsets:
                members.append(
                    f"  val {field.upper()}: Int = {width_expression(self.abi.offset(record, field))}"
                )
            objects.append(
                f"internal object {public} {{\n" + "\n".join(members) + "\n}"
            )
        return (
            HEADER
            + f"package {PACKAGE}\n\n"
            + "import org.maplibre.nativeffi.internal.memory.w\n\n"
            + "\n\n".join(objects)
            + "\n"
        )

    def ffm_layout(self, kind):
        """The FFM layout expression of a C type inside a record."""
        if isinstance(kind, Primitive):
            return "ADDRESS" if kind is POINTER else FFM[kind.name]
        if isinstance(kind, Array):
            return f"Ffm.array({kind.length}, {self.ffm_layout(kind.element)})"
        self.record_layout(kind)
        return kind.name

    def record_layout(self, kind):
        # Nested layouts come first: an object initializes its properties in order.
        if kind.name in self.layouts:
            return
        layout = self.abi.record(kind, 64)
        members, cursor = [], 0
        for field, child in kind.fields:
            offset = layout.offsets[field]
            if not kind.union and offset > cursor:
                members.append(f"Ffm.pad({offset - cursor})")
            members.append(f'{self.ffm_layout(child)}.withName("{field}")')
            size, _align = self.abi.size_align(child, 64)
            cursor = max(cursor, offset + size) if not kind.union else max(cursor, size)
        if layout.size > cursor:
            members.append(f"Ffm.pad({layout.size - cursor})")
        builder = "Ffm.union" if kind.union else "Ffm.struct"
        self.layouts[kind.name] = (
            f"internal val {kind.name}: GroupLayout = {builder}({', '.join(members)})"
        )

    def ffm_argument(self, kind):
        if isinstance(kind, Record):
            self.record_layout(kind)
            return kind.name
        return FFM[kind.name]

    def jvm(self):
        handles, functions = [], []
        for s in self.signatures:
            parameters = [p for p in s.parameters if not p.returned]
            layouts = [self.ffm_argument(p.kind) for p in parameters]
            result = "null" if s.result is None else self.ffm_argument(s.result)
            handles.append(
                f'  private val {s.function} = Ffm.downcall("{s.function}", {", ".join([result, *layouts])})'
            )
            arguments = [
                f"Ffm.value({p.name}, {p.kind.name})"
                if isinstance(p.kind, Record)
                else p.name
                for p in parameters
            ]
            if isinstance(s.result, Record):
                arguments.insert(0, f"Ffm.into(returned, {s.result.name})")
                call = (
                    f"{s.function}.invokeExact({', '.join(arguments)}) as MemorySegment"
                )
                functions.append(
                    f"  actual fun {s.function}({self.kotlin_parameters(s)}) {{ {call} }}"
                )
            elif s.result is None:
                functions.append(
                    f"  actual fun {s.function}({self.kotlin_parameters(s)}) {{ {s.function}.invoke({', '.join(arguments)}) }}"
                )
            else:
                functions.append(
                    f"  actual fun {s.function}({self.kotlin_parameters(s)}): {s.carrier} = "
                    f"{s.function}.invokeExact({', '.join(arguments)}) as {s.carrier}"
                )
        stubs = []
        for site in self.sites:
            arguments = []
            for _local, ctype, _carrier in site.parameters:
                arguments.append(self.ffm_argument(self.abi.classify(ctype)))
            result = self.classify(site.result)
            stubs.append(
                f'  actual val {site.name}: Long = Ffm.upcall({site.owner}::class.java, "{site.name}", '
                + ", ".join(
                    [
                        "null" if result is None else self.ffm_argument(result),
                        *arguments,
                    ]
                )
                + ")"
            )
        imports = (
            "import java.lang.foreign.GroupLayout\n"
            "import java.lang.foreign.MemorySegment\n"
            "import java.lang.foreign.ValueLayout.*\n\n"
        )
        layouts = [self.layouts[name] for name in self.layouts]
        return {
            "C.kt": HEADER
            + f"package {PACKAGE}\n\n"
            + imports
            + "/** The FFM downcall behind each C function. */\n"
            + "internal actual object C {\n"
            + "\n".join(handles)
            + "\n\n"
            + "\n".join(functions)
            + "\n}\n\n"
            + "// The layout of each record that C passes or returns by value, nested ones first.\n"
            + "\n".join(layouts)
            + "\n",
            "UpcallStubs.kt": HEADER
            + f"package {PACKAGE}\n\n"
            + "import java.lang.foreign.ValueLayout.*\n\n"
            + "internal actual object UpcallStubs {\n"
            + "\n".join(stubs)
            + "\n}\n",
        }

    def opaque(self, ctype):
        """Whether a pointer type points to void, which cinterop imports as COpaquePointer."""
        pointee = ctype.pointee
        if pointee is None and ctype.kind == "typedef":
            typedef = self.bound.source.typedefs_by_name.get(ctype.declaration)
            pointee = typedef.type.pointee if typedef else None
        return pointee is not None and (
            pointee.kind == "void" or pointee.spelling.removeprefix("const ") == "void"
        )

    def cinterop_type(self, ctype):
        kind = self.abi.classify(ctype)
        if isinstance(kind, Record):
            return f"CValue<{kind.name}>"
        if kind is POINTER:
            pointee = ctype.pointee
            if pointee is None and ctype.kind == "typedef":
                pointee = self.bound.source.typedefs_by_name[
                    ctype.declaration
                ].type.pointee
            if (
                pointee is None
                or pointee.kind == "void"
                or pointee.spelling.endswith("void")
            ):
                return "COpaquePointer?"
            if pointee.kind in {
                "char_s",
                "char_u",
                "schar",
                "uchar",
            } or pointee.spelling.removeprefix("const ") in {
                "char",
                "unsigned char",
                "signed char",
            }:
                return "CPointer<ByteVar>?"
            target = self.abi.classify(pointee)
            if isinstance(target, Record):
                return f"CPointer<{target.name}>?"
            raise ValueError(f"{ctype.spelling}: no cinterop pointer rule")
        return CINTEROP_TYPE[kind.name]

    def native(self):
        functions = []
        for s in self.signatures:
            parameters = [p for p in s.parameters if not p.returned]
            arguments = []
            for p in parameters:
                if isinstance(p.kind, Record):
                    arguments.append(
                        f"{p.name}.toCPointer<{p.kind.name}>()!!.pointed.readValue()"
                    )
                elif p.kind is POINTER and self.opaque(p.ctype):
                    # Kotlin cannot infer the pointee of an opaque pointer parameter.
                    arguments.append(f"{p.name}.toCPointer<CPointed>()")
                else:
                    arguments.append(p.name + TO_CINTEROP[p.kind.name])
            call = f"{CINTEROP}.{s.function}({', '.join(arguments)})"
            head = f"  actual fun {s.function}({self.kotlin_parameters(s)})"
            if isinstance(s.result, Record):
                functions.append(f"{head} {{ {call}.place(returned.toCPointer()!!) }}")
            elif s.result is None:
                functions.append(f"{head} {{ {call} }}")
            else:
                functions.append(
                    f"{head}: {s.carrier} = {call}{FROM_CINTEROP[s.result.name]}"
                )
        stubs = []
        for site in self.sites:
            parameters, arguments, records = [], [], []
            for local, ctype, _carrier in site.parameters:
                parameters.append(f"{local}: {self.cinterop_type(ctype)}")
                kind = self.abi.classify(ctype)
                if isinstance(kind, Record):
                    records.append(local)
                    arguments.append(f"{local}Address")
                else:
                    arguments.append(local + FROM_CINTEROP[kind.name])
            call = f"{site.owner}.{site.name}({', '.join(arguments)})"
            result = self.classify(site.result)
            if result is not None:
                call += TO_CINTEROP[result.name]
            for local in reversed(records):
                call = f"{local}.useContents {{ val {local}Address = ptr.toLong(); {call} }}"
            stubs.append(
                f"  actual val {site.name}: Long = staticCFunction {{ {', '.join(parameters)} -> {call} }}.toLong()"
            )
        return {
            "C.kt": HEADER
            + "@file:OptIn(kotlinx.cinterop.ExperimentalForeignApi::class)\n\n"
            + f"package {PACKAGE}\n\n"
            + "import kotlinx.cinterop.*\n"
            + f"import {CINTEROP}.*\n\n"
            + "/** The cinterop call behind each C function. */\n"
            + "internal actual object C {\n"
            + "\n".join(functions)
            + "\n}\n",
            "UpcallStubs.kt": HEADER
            + "@file:OptIn(kotlinx.cinterop.ExperimentalForeignApi::class)\n\n"
            + f"package {PACKAGE}\n\n"
            + "import kotlinx.cinterop.*\n"
            + "import platform.posix.size_t\n"
            + f"import {CINTEROP}.*\n\n"
            + "internal actual object UpcallStubs {\n"
            + "\n".join(stubs)
            + "\n}\n",
        }

    def android(self):
        externals = [
            ("  @CriticalNative\n" if s.function in self.critical else "")
            + f"  @JvmStatic actual external fun {s.function}({self.kotlin_parameters(s)}): {s.carrier}"
            for s in self.signatures
        ]
        stubs = [
            f'  actual val {site.name}: Long = Jni.upcallStub("{site.name}")'
            for site in self.sites
        ]
        kotlin = (
            HEADER
            + f"package {PACKAGE}\n\n"
            + "import dalvik.annotation.optimization.CriticalNative\n\n"
            + "/** The JNI native behind each C function, registered by `src/androidMain/jni`. */\n"
            + "internal actual object C {\n"
            + "  init {\n    Jni.load()\n  }\n\n"
            + "\n".join(externals)
            + "\n}\n"
        )
        upcall_stubs = (
            HEADER
            + f"package {PACKAGE}\n\n"
            + "internal actual object UpcallStubs {\n"
            + "\n".join(stubs)
            + "\n}\n"
        )
        return {"C.kt": kotlin, "UpcallStubs.kt": upcall_stubs}, self.jni()

    def c_argument(self, parameter):
        kind, ctype = parameter.kind, parameter.ctype
        spelling = ctype.spelling
        if isinstance(kind, Record):
            return (
                f"MLN_JNI_RECORD({ctype.declaration or spelling}, {parameter.c_name})"
            )
        if kind is POINTER:
            return f"MLN_JNI_POINTER({spelling}, {parameter.c_name})"
        return f"({spelling}){parameter.c_name}"

    def release(self, handle, local):
        """The C statement that releases a handle a callback owns when its host throws."""
        from .kotlin_operations import disposer_arguments

        function = self.bound.source.functions_by_name[handle.release]
        arguments = disposer_arguments(handle, function, local, "NULL")
        if function.diagnostic:
            arguments.append("NULL")
        return f"{handle.release}({', '.join(arguments)});"

    def jni(self):
        functions, methods, critical_methods = [], [], []
        for s in self.signatures:
            carriers = [f"{JNI_TYPE[p.carrier]} {p.c_name}" for p in s.parameters]
            parameters = ["JNIEnv* env", "jclass type", *carriers]
            arguments = [self.c_argument(p) for p in s.parameters if not p.returned]
            call = f"{s.function}({', '.join(arguments)})"
            if isinstance(s.result, Record):
                body = (
                    f"*MLN_JNI_POINTER({s.result_ctype.spelling}*, returned) = {call};"
                )
            elif s.result is None:
                body = f"{call};"
            elif s.result is POINTER:
                body = f"return MLN_JNI_ADDRESS({call});"
            else:
                body = f"return ({JNI_TYPE[s.carrier]}){call};"
            if s.function in self.critical:
                functions.append(
                    f"static {JNI_TYPE[s.carrier]} {s.function}_critical({', '.join(carriers) or 'void'}) {{\n  {body}\n}}"
                )
                forward = f"{s.function}_critical({', '.join(p.c_name for p in s.parameters)});"
                body = ("return " if s.carrier != "Unit" else "") + forward
            functions.append(
                f"static {JNI_TYPE[s.carrier]} {s.function}_jni({', '.join(parameters)}) {{\n  {body}\n}}"
            )
            descriptor = (
                "("
                + "".join(JNI_LETTER[p.carrier] for p in s.parameters)
                + ")"
                + JNI_LETTER[s.carrier]
            )
            methods.append(
                f'  {{"{s.function}", "{descriptor}", (void*){s.function}_jni}},'
            )
            target = "critical" if s.function in self.critical else "jni"
            critical_methods.append(
                f'  {{"{s.function}", "{descriptor}", (void*){s.function}_{target}}},'
            )
        upcalls, entries, pointers, stubs = [], [], [], []
        for site in self.sites:
            parameters, values = [], []
            for local, ctype, carrier in site.parameters:
                c_name = local
                parameters.append(self.c_declaration(ctype, c_name))
                kind = self.abi.classify(ctype)
                if isinstance(kind, Record):
                    values.append(f"{{.j = MLN_JNI_ADDRESS(&{c_name})}}")
                elif kind is POINTER:
                    values.append(f"{{.j = MLN_JNI_ADDRESS({c_name})}}")
                else:
                    values.append(
                        f"{{.{JVALUE[carrier]} = ({JNI_TYPE[carrier]}){c_name}}}"
                    )
            result = self.classify(site.result)
            arguments = (
                f"jvalue arguments[] = {{{', '.join(values)}}};" if values else ""
            )
            array = "arguments" if values else "NULL"
            upcall = f"&mln_jni_{site.name}_upcall"
            if result is None:
                body = f"mln_jni_upcall_void({upcall}, {array});"
                callback = self.bound.callbacks.get(site.callback)
                releases = (
                    [
                        self.release(parameter.value.handle, identifier(parameter.name))
                        for parameter in callback.arguments
                        if parameter.value.kind == "handle"
                        and parameter.value.ownership == "owned"
                    ]
                    if callback
                    else []
                )
                if releases:
                    body = (
                        f"if (!mln_jni_upcall_void({upcall}, {array})) {{\n"
                        + "".join(f"    {release}\n" for release in releases)
                        + "  }"
                    )
                c_result = "void"
            else:
                width = {"Long": "long", "Boolean": "boolean"}.get(
                    site.result_carrier, "int"
                )
                body = (
                    f"{JNI_TYPE[site.result_carrier]} result = {site.failure};\n"
                    f"  mln_jni_upcall_{width}({upcall}, {array}, &result);\n"
                    f"  return ({site.result.spelling})result;"
                )
                c_result = site.result.spelling
            upcalls.append(
                f"static {c_result} mln_jni_{site.name}({', '.join(parameters) or 'void'}) {{\n"
                + (f"  {arguments}\n" if arguments else "")
                + f"  {body}\n}}"
            )
            descriptor = (
                "("
                + "".join(JNI_LETTER[carrier] for _l, _c, carrier in site.parameters)
                + ")"
                + JNI_LETTER[site.result_carrier]
            )
            owner = f"{PACKAGE.replace('.', '/')}/{site.owner}"
            entries.append(
                f'static mln_jni_upcall mln_jni_{site.name}_upcall = {{"{owner}", "{site.name}", "{descriptor}", NULL}};'
            )
            pointers.append(f"  &mln_jni_{site.name}_upcall,")
            stubs.append(f"  (void*)mln_jni_{site.name},")
        return (
            HEADER
            + "// The JNI half of each C function and upcall the Kotlin binding uses. Every\n"
            + "// argument is a primitive; mln_jni.h defines the casts and mln_jni.c the rest.\n"
            + '#include "mln_jni.h"\n\n'
            + "#include <maplibre_native_c.h>\n"
            + "#include <maplibre_native_c/plugin.h>\n\n"
            + "\n\n".join(functions)
            + "\n\nconst JNINativeMethod mln_jni_methods[] = {\n"
            + "\n".join(methods)
            + "\n};\nconst size_t mln_jni_method_count =\n"
            + "  sizeof mln_jni_methods / sizeof mln_jni_methods[0];\n\n"
            + "const JNINativeMethod mln_jni_critical_methods[] = {\n"
            + "\n".join(critical_methods)
            + "\n};\n\n"
            + "\n".join(entries)
            + "\n\n"
            + "\n\n".join(upcalls)
            + "\n\nmln_jni_upcall* const mln_jni_upcalls[] = {\n"
            + "\n".join(pointers)
            + "\n};\n\nvoid* const mln_jni_upcall_stubs[] = {\n"
            + "\n".join(stubs)
            + "\n};\nconst size_t mln_jni_upcall_count =\n"
            + "  sizeof mln_jni_upcall_stubs / sizeof mln_jni_upcall_stubs[0];\n"
        )

    def wasm_kind(self, kind):
        """The primitive that carries [kind] across wasm32: a record crosses by address."""
        return POINTER if isinstance(kind, Record) else kind

    def wasm_cast(self, parameter, value):
        """The C argument that a wasm wrapper passes for [parameter], from its carrier [value]."""
        ctype = parameter.ctype
        if isinstance(parameter.kind, Record):
            return f"*(const {ctype.declaration or ctype.spelling}*)(uintptr_t){value}"
        return f"({ctype.spelling}){value}"

    def wasm(self):
        """The wasm shim: the Kotlin externs, the C wrappers they call, the export
        list, the upcall stubs that the browser module serves, and the
        trampolines behind them.

        A function whose header records `blocks=thread_start` cannot run on the
        page, which cannot wait for a thread to start. Its wrapper copies the
        arguments into the thread start that `ThreadStart` staged, starts the call
        on a pthread, and returns at once; the page later receives the call's
        status.
        """
        externs, functions, wrappers, exports = [], [], [], []
        for s in self.signatures:
            names = [f"p{index}" for index in range(len(s.parameters) + bool(s.blocks))]
            carriers = [self.wasm_kind(p.kind) for p in s.parameters]
            extern_types = [WASM[kind.name][0] for kind in carriers]
            arguments = [
                WASM[kind.name][2].format(p.name)
                for p, kind in zip(s.parameters, carriers, strict=True)
            ]
            if s.blocks:
                extern_types.insert(0, "Int")
                arguments.insert(0, "ThreadStart.staged()")
            result = (
                None if s.result is None or isinstance(s.result, Record) else s.result
            )
            extern_result = "Unit" if result is None else WASM[result.name][0]
            extern = f"_{s.wrapper}"
            externs.append(
                f"private fun {s.wrapper}("
                + ", ".join(
                    f"{n}: {t}" for n, t in zip(names, extern_types, strict=True)
                )
                + f"): {extern_result} =\n"
                + f'  js("{WASM_MODULE}.{extern}({", ".join(names)})")'
            )
            call = f"{s.wrapper}({', '.join(arguments)})"
            head = f"  actual fun {s.function}({self.kotlin_parameters(s)})"
            if result is None:
                functions.append(f"{head} {{ {call} }}")
            else:
                functions.append(
                    f"{head}: {s.carrier} = {WASM[result.name][3].format(call)}"
                )
            wrappers.append(self.wasm_wrapper(s, carriers, result))
            exports.append(extern)
        index = {site.name: number for number, site in enumerate(self.dispatched)}
        stubs = []
        for site in self.sites:
            if site.name in index:
                getter = f"upcallFunction({index[site.name]})"
            else:
                getter = (
                    "throw MaplibreException(Status.UNSUPPORTED, "
                    f'"{site.name} needs Kotlin on a native thread, which Kotlin/Wasm cannot run")'
                )
            stubs.append(f"  actual val {site.name}: Long\n    get() = {getter}")
        for site in self.dispatched:
            if site.split:
                stubs.append(
                    f"  val {site.name}: Long\n    get() = upcallFunction({index[site.name]})"
                )
        kotlin = (
            HEADER
            + "@file:OptIn(ExperimentalWasmJsInterop::class)\n\n"
            + f"package {PACKAGE}\n\n"
            + "import org.maplibre.nativeffi.internal.call.ThreadStart\n\n"
            + "/** The C wrapper behind each C function, in the module that `loadWasmModule` loads. */\n"
            + "internal actual object C {\n"
            + "\n".join(functions)
            + "\n}\n\n"
            + "\n\n".join(externs)
            + "\n"
        )
        upcall_stubs = (
            HEADER
            + "@file:OptIn(ExperimentalWasmJsInterop::class)\n\n"
            + f"package {PACKAGE}\n\n"
            + "import org.maplibre.nativeffi.MaplibreException\n"
            + "import org.maplibre.nativeffi.Status\n\n"
            + "/**\n"
            + " * The browser module serves each site that the binding's delivery queue carries, with a\n"
            + " * trampoline that the page's dispatch calls. A site that native calls on its own thread has no\n"
            + " * function pointer.\n"
            + " */\n"
            + "internal actual object UpcallStubs {\n"
            + "\n".join(stubs)
            + "\n}\n\n"
            + "private fun upcallFunction(site: Int): Long = unsignedWord(mln_kw_upcall_function(site))\n\n"
            + "private fun mln_kw_upcall_function(site: Int): Int =\n"
            + f'  js("{WASM_MODULE}._mln_kw_upcall_function(site)")\n'
        )
        c = (
            HEADER
            + "// The C half of each wasm extern of the Kotlin binding, and the trampoline\n"
            + "// of each site that the binding's delivery queue carries. Every argument is a\n"
            + "// primitive that wasm32 passes to JavaScript, and a record crosses by\n"
            + "// address.\n"
            + '#include "mln_kw_runtime.h"\n\n'
            + "#include <maplibre_native_c.h>\n"
            + "#include <maplibre_native_c/plugin.h>\n"
            + "#include <stddef.h>\n\n"
            + "\n\n".join(wrappers)
            + "\n\n"
            + self.trampolines()
        )
        return (
            {
                "C.kt": kotlin,
                "UpcallStubs.kt": upcall_stubs,
                "DispatchedUpcalls.kt": self.dispatched_upcalls(),
            },
            c,
            "\n".join([*exports, "_mln_kw_upcall_function"]) + "\n",
        )

    def trampolines(self):
        """The trampoline of each dispatched site, and the table that Kotlin reads
        their function pointers from.

        A trampoline copies each argument into its own zeroed 8-byte slot, a
        record as its address, with the builtin memcpy, since the glue includes
        no libc header, and hands the slots to the page, which reads
        them in `DispatchedUpcalls`. The queue answers native in place of the
        callback, so a trampoline returns the callback's queue result.
        """
        functions = []
        for number, site in enumerate(self.dispatched):
            parameters, copies = [], []
            for slot, (local, ctype, _carrier) in enumerate(site.parameters):
                parameters.append(self.c_declaration(ctype, local))
                source = local
                if isinstance(self.abi.classify(ctype), Record):
                    source = f"{local}_address"
                    copies.append(
                        f"  const {ctype.declaration or ctype.spelling}* {source} = &{local};"
                    )
                copies.append(
                    f"  __builtin_memcpy(&arguments[{slot}], &{source}, sizeof {source});"
                )
            result = self.classify(site.result)
            answer = ""
            if result is not None:
                answer = (
                    f"  return {self.bound.callbacks[site.callback].queue_result};\n"
                )
            functions.append(
                f"static {site.result.spelling if result is not None else 'void'} "
                f"mln_kw_upcall_{site.name}({', '.join(parameters) or 'void'}) {{\n"
                f"  uint64_t arguments[{max(len(site.parameters), 1)}] = {{0}};\n"
                + "".join(f"{copy}\n" for copy in copies)
                + f"  mln_kw_js_upcall({number}, arguments);\n"
                + answer
                + "}"
            )
        table = "".join(
            f"    (void (*)(void))mln_kw_upcall_{site.name},\n"
            for site in self.dispatched
        )
        return (
            "\n\n".join(functions)
            + "\n\n"
            + "/** The function pointer of the trampoline of [site], or 0 past the last. */\n"
            + "uintptr_t mln_kw_upcall_function(uint32_t site) {\n"
            + "  static void (*const functions[])(void) = {\n"
            + table
            + "  };\n"
            + "  return site < sizeof functions / sizeof functions[0]\n"
            + "           ? (uintptr_t)functions[site]\n"
            + "           : 0;\n"
            + "}\n"
        )

    def dispatched_upcalls(self):
        """`DispatchedUpcalls`: the site that each trampoline names, with the
        arguments in its slots."""
        branches = []
        for number, site in enumerate(self.dispatched):
            arguments = []
            for slot, (_local, ctype, _carrier) in enumerate(site.parameters):
                address = f"arguments + {8 * slot}" if slot else "arguments"
                kind = self.abi.classify(ctype)
                if isinstance(kind, Record):
                    kind = POINTER
                arguments.append(WASM_READ[kind.name].format(address))
            branches.append(
                f"      {number} -> {site.owner}.{site.name}({', '.join(arguments)})"
            )
        return (
            HEADER
            + f"package {PACKAGE}\n\n"
            + "import org.maplibre.nativeffi.internal.memory.*\n\n"
            + "/**\n"
            + " * Runs the site of each trampoline that the browser module's dispatch calls, with the\n"
            + " * arguments that the trampoline copied into 8-byte slots.\n"
            + " */\n"
            + "internal object DispatchedUpcalls {\n"
            + "  /** Runs the site numbered [site] with the slots at [arguments]. */\n"
            + "  fun run(site: Int, arguments: Long) {\n"
            + "    when (site) {\n"
            + "\n".join(branches)
            + '\n      else -> error("the browser module called an unknown upcall site $site")\n'
            + "    }\n  }\n}\n"
        )

    def wasm_wrapper(self, s, carriers, result):
        parameters = [
            f"{WASM[kind.name][1]} {p.c_name}"
            for p, kind in zip(s.parameters, carriers, strict=True)
        ]
        c_result = "void" if result is None else WASM[result.name][1]
        if s.blocks:
            arguments = f"{s.wrapper}_arguments"
            fields = "".join(f"  {parameter};\n" for parameter in parameters)
            casts = [
                self.wasm_cast(p, f"call->{p.c_name}")
                for p in s.parameters
                if not p.returned
            ]
            return (
                f"typedef struct {arguments} {{\n{fields}}} {arguments};\n"
                f"_Static_assert(sizeof({arguments}) <= MLN_KW_THREAD_START_ARGUMENTS_SIZE, "
                f'"{s.function} arguments");\n\n'
                f"static int32_t {s.wrapper}_run(const void* arguments) {{\n"
                f"  const {arguments}* call = arguments;\n"
                f"  return (int32_t){s.function}({', '.join(casts)});\n}}\n\n"
                f"int32_t {s.wrapper}({', '.join(['uintptr_t start', *parameters])}) {{\n"
                f"  {arguments} arguments = {{"
                + ", ".join(p.c_name for p in s.parameters)
                + "};\n"
                f"  return mln_kw_start_thread((mln_kw_thread_start*)start, {s.wrapper}_run, "
                "&arguments, sizeof arguments);\n}"
            )
        casts = [self.wasm_cast(p, p.c_name) for p in s.parameters if not p.returned]
        call = f"{s.function}({', '.join(casts)})"
        if isinstance(s.result, Record):
            body = f"*({s.result_ctype.spelling}*)returned = {call};"
        elif result is None:
            body = f"{call};"
        else:
            body = f"return ({c_result}){call};"
        return f"{c_result} {s.wrapper}({', '.join(parameters) or 'void'}) {{\n  {body}\n}}"

    def c_declaration(self, ctype, local):
        spelling = ctype.spelling
        return (
            f"{spelling} {local}"
            if not spelling.endswith("*")
            else f"{spelling}{local}"
        )
