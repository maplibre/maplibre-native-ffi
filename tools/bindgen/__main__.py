"""Generate the bindings, or render them unformatted into a snapshot directory.

Generation fails before it writes anything while a binding cannot lower a
declaration.
"""

from __future__ import annotations

import argparse
import importlib
import json
import subprocess
import sys
from pathlib import Path

from . import native_capture
from .compiler import compile_api
from .frontend import parse_headers
from .model import Api, ModelError
from .schema import validate

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = "bindings/generated-files.json"
LANGUAGES = (
    "dart",
    "dotnet",
    "go",
    "kotlin",
    "python",
    "rust",
    "swift",
    "typescript",
    "zig",
)


def render(api: Api) -> tuple[dict[str, str], dict[str, dict[str, str]]]:
    """The outputs by repository path, and each binding's unsupported
    declarations with their reasons."""
    from . import native_results

    bound = compile_api(api)
    if bound.diagnostics:
        raise ModelError(list(bound.diagnostics))
    outputs = native_capture.generate(bound)
    outputs.update(native_results.generate(bound))
    unsupported = {}
    for language in LANGUAGES:
        lowered = importlib.import_module(f".emitters.{language}", __package__).lower(
            bound
        )
        outputs.update(lowered.files)
        if lowered.unsupported:
            unsupported[language] = lowered.unsupported
    generated_binding_paths = {
        path.removeprefix("bindings/")
        for path in outputs
        if path.startswith("bindings/")
    }
    generated_binding_paths.update(
        {".gitattributes", MANIFEST.removeprefix("bindings/")}
    )
    outputs["bindings/.gitattributes"] = (
        "# Generated by tools/bindgen. Do not edit.\n"
        + "".join(
            f"/{path} linguist-generated=true\n"
            for path in sorted(generated_binding_paths)
        )
    )
    outputs[MANIFEST] = json.dumps({"files": sorted(outputs)}, indent=2) + "\n"
    return outputs, unsupported


def write(outputs: dict[str, str], root: Path) -> None:
    for path, source in outputs.items():
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(source)


def format_files(paths: list[str], root: Path) -> None:
    """Format and lint-fix the files under `root` as `mise run fix` would."""
    subprocess.run(
        ["hk", "fix", "--files0-from", "-"],
        input="\0".join(paths),
        text=True,
        cwd=root,
        check=True,
    )


def previous_outputs(root: Path) -> set[str]:
    """Read the outputs that the last run recorded in its manifest."""
    manifest = root / MANIFEST
    if not manifest.is_file():
        return set()
    return set(json.loads(manifest.read_text())["files"])


def complete(unsupported: dict[str, dict[str, str]]) -> bool:
    """Print each binding's unsupported declarations, and whether it has none."""
    for language, missing in sorted(unsupported.items()):
        print(f"{language}: {len(missing)} declarations require implementation")
        for name, reason in sorted(missing.items()):
            print(f"  {name}: {reason}")
    return not unsupported


def generate(api: Api, root: Path = ROOT) -> int:
    """Write and format the outputs under `root` and return the exit status.

    A file that the previous run recorded and this run no longer writes is
    stale, and generation deletes it.
    """
    outputs, unsupported = render(api)
    if not complete(unsupported):
        return 1
    previous = previous_outputs(root)
    for path in previous - outputs.keys():
        (root / path).unlink(missing_ok=True)
    write(outputs, root)
    format_files(list(outputs), root)
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("generate", "render"))
    parser.add_argument(
        "--out", type=Path, help="the directory that render writes its snapshot to"
    )
    parser.add_argument("--include", type=Path, default=ROOT / "include")
    parser.add_argument(
        "--native-include",
        type=Path,
        default=ROOT / "third_party/maplibre-native/include",
    )
    parser.add_argument("--clang", default="clang")
    parser.add_argument("--clang-arg", action="append", default=[])
    args = parser.parse_args()
    if (args.command == "render") != (args.out is not None):
        parser.error("--out goes with render, and render requires it")

    try:
        api = parse_headers(
            args.include,
            clang=args.clang,
            clang_args=(f"-I{args.native_include.resolve()}", *args.clang_arg),
        )
        validate(api)
        if args.command == "generate":
            return generate(api)
        outputs, unsupported = render(api)
        if not complete(unsupported):
            return 1
        write(outputs, args.out)
        return 0
    except (ModelError, OSError, subprocess.CalledProcessError) as error:
        print(error, file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
