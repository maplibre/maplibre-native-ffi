"""Generate bindings and report the declarations that lack lowering rules."""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

from . import native_capture
from .compiler import compile_api
from .frontend import parse_headers
from .model import Api, ModelError
from .schema import validate

ROOT = Path(__file__).resolve().parents[2]
COVERAGE = "bindings/generated-coverage.json"


def render(api: Api) -> tuple[dict[str, str], dict]:
    from . import native_results
    from .emitters import (
        dart,
        dart_native,
        dotnet,
        go,
        kotlin,
        python,
        rust,
        swift,
        typescript,
        zig,
    )

    bound = compile_api(api)
    if bound.diagnostics:
        raise ModelError(list(bound.diagnostics))
    outputs = native_capture.generate(bound)
    outputs.update(native_results.generate(bound))
    for directory, emitter in (
        ("bindings/go/maplibre", go),
        ("bindings/dotnet/src/Maplibre.NativeFfi", dotnet),
        ("bindings/rust", rust),
        ("bindings/python", python),
        ("bindings/swift/Sources/MaplibreNativeFFI", swift),
        ("bindings/kotlin", kotlin),
        ("bindings/zig/src", zig),
    ):
        outputs.update(
            {
                f"{directory}/{path}": source
                for path, source in emitter.generate(bound).items()
            }
        )
    outputs["bindings/dart/lib/src/runtime/generated_operations.dart"] = dart.generate(
        bound
    )
    outputs["bindings/dart/lib/src/generated_values.dart"] = dart.generate_values(bound)
    outputs[dart_native.PATH] = dart_native.generate(bound)
    outputs.update(typescript.generate(bound))
    reports = {
        language: emitter.coverage(bound)
        for language, emitter in {
            "dotnet": dotnet,
            "go": go,
            "rust": rust,
            "python": python,
            "swift": swift,
            "typescript": typescript,
            "dart": dart,
            "kotlin": kotlin,
            "zig": zig,
        }.items()
    }
    generated_binding_paths = {
        path.removeprefix("bindings/")
        for path in outputs
        if path.startswith("bindings/")
    }
    generated_binding_paths.update({".gitattributes", "generated-coverage.json"})
    outputs["bindings/.gitattributes"] = (
        "# Generated by tools/bindgen. Do not edit.\n"
        + "".join(
            f"/{path} linguist-generated=true\n"
            for path in sorted(generated_binding_paths)
        )
    )
    report = {"files": sorted(outputs)}
    unsupported = {
        language: coverage["unsupported"]
        for language, coverage in reports.items()
        if coverage["unsupported"]
    }
    if unsupported:
        report["unsupported"] = unsupported
    outputs[COVERAGE] = json.dumps(report, indent=2, sort_keys=True) + "\n"
    return outputs, report


def format_files(paths: list[str], root: Path) -> None:
    """Format and lint-fix the files under `root` as `mise run fix` would."""
    subprocess.run(
        ["hk", "fix", "--files0-from", "-"],
        input="\0".join(paths),
        text=True,
        cwd=root,
        check=True,
    )


def previous_outputs(root: Path) -> set[str]:
    """Read the outputs that the last run recorded in its coverage report."""
    manifest = root / COVERAGE
    if not manifest.is_file():
        return set()
    return set(json.loads(manifest.read_text())["files"])


def generate(api: Api, require_complete: bool, root: Path = ROOT) -> int:
    """Write and format the outputs under `root` and return the exit status.

    A file that the previous run recorded and this run no longer writes is
    stale, and generation deletes it.
    """
    previous = previous_outputs(root)
    outputs, report = render(api)
    for path in previous - outputs.keys():
        (root / path).unlink(missing_ok=True)
    for path, source in outputs.items():
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(source)
    format_files(list(outputs), root)
    for language, missing in sorted(report.get("unsupported", {}).items()):
        print(f"{language}: {len(missing)} declarations require implementation")
    return int(require_complete and bool(report.get("unsupported")))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("generate",))
    parser.add_argument("--include", type=Path, default=ROOT / "include")
    parser.add_argument(
        "--native-include",
        type=Path,
        default=ROOT / "third_party/maplibre-native/include",
    )
    parser.add_argument("--clang", default="clang")
    parser.add_argument("--clang-arg", action="append", default=[])
    parser.add_argument("--require-complete", action="store_true")
    args = parser.parse_args()

    try:
        api = parse_headers(
            args.include,
            clang=args.clang,
            clang_args=(f"-I{args.native_include.resolve()}", *args.clang_arg),
        )
        validate(api)
        return generate(api, args.require_complete)
    except (ModelError, OSError, subprocess.CalledProcessError) as error:
        print(error, file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
