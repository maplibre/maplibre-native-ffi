"""The generate command's exit status drives CI, and its writes keep the tree current."""

import contextlib
import io
import sys
import unittest
from pathlib import Path
from tempfile import TemporaryDirectory
from unittest.mock import patch

from support import parse, protocol_header

from tools.bindgen import __main__ as cli

# Formatting belongs to the language tools. These tests keep emitted text as is.
UNFORMATTED = patch.object(cli, "format_files", lambda _paths, _root: None)


class GenerateCommandTests(unittest.TestCase):
    def generate(self, root, groups):
        """Run generate under `root`, returning its status and diagnostics."""
        errors = io.StringIO()
        with (
            UNFORMATTED,
            contextlib.redirect_stdout(io.StringIO()),
            contextlib.redirect_stderr(errors),
        ):
            status = cli.generate(parse(groups=groups), root=root)
        return status, errors.getvalue()

    def test_previous_outputs_that_are_no_longer_generated_are_stale(self):
        # The conventions group adds a record that the dotnet emitter writes
        # to a file of its own.
        removed = "bindings/dotnet/src/Maplibre.NativeFfi/Api/Label.g.cs"
        # Only the previous run's output list decides what is stale, never a
        # file's header line.
        handwritten = "bindings/rust/src/handwritten.rs"
        with TemporaryDirectory() as directory:
            root = Path(directory)
            self.assertEqual(self.generate(root, ("keywords", "conventions"))[0], 0)
            self.assertTrue((root / removed).is_file())
            (root / handwritten).parent.mkdir(parents=True, exist_ok=True)
            (root / handwritten).write_text(
                "// Generated by tools/bindgen; DO NOT EDIT.\n"
            )

            self.assertEqual(self.generate(root, ("keywords",)), (0, ""))
            self.assertFalse((root / removed).exists())
            self.assertTrue((root / handwritten).is_file())

    def test_the_values_group_fails_generation_before_writing_output(self):
        # The values group declares a nullable counted input that the Rust
        # emitter reports unsupported.
        with TemporaryDirectory() as directory:
            root = Path(directory)
            self.assertEqual(self.generate(root, ("keywords",))[0], 0)
            manifest = (root / cli.MANIFEST).read_text()
            output = io.StringIO()
            with UNFORMATTED, contextlib.redirect_stdout(output):
                status = cli.generate(parse(groups=("values",)), root=root)
            self.assertEqual(status, 1)
            self.assertIn(
                "rust: 1 declarations require implementation", output.getvalue()
            )
            self.assertIn("mln_probe_roundtrip", output.getvalue())
            # The previous run's outputs stay as they were.
            self.assertEqual((root / cli.MANIFEST).read_text(), manifest)

    def test_invalid_headers_fail_before_writing_output(self):
        with TemporaryDirectory() as directory:
            include = Path(directory)
            (include / "api.h").write_text(
                protocol_header("mln_typo mln_broken(void);")
            )
            arguments = ["bindgen", "generate", "--include", str(include)]
            errors = io.StringIO()
            with (
                patch.object(sys, "argv", arguments),
                patch.object(cli, "generate") as generate,
                contextlib.redirect_stderr(errors),
            ):
                self.assertEqual(cli.main(), 1)
            generate.assert_not_called()
            self.assertIn("unknown type name", errors.getvalue())


if __name__ == "__main__":
    unittest.main()
