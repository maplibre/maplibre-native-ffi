"""Generate CI workflows from coverage units and native target commands."""

from __future__ import annotations

import argparse
import difflib
import io
import pathlib
import re
import sys

from ruamel.yaml import YAML
from ruamel.yaml.comments import CommentedMap
from ruamel.yaml.scalarstring import LiteralScalarString

from ci.action_pins import catalog
from ci.coverage import HYGIENE, dependencies, job_name, job_units
from ci.workflow import (
    LINUX_RUNNER,
    SMALL_RUNNER,
    load_configuration,
    runner,
    target_rows,
)

ROOT = pathlib.Path(__file__).resolve().parents[1]
GENERATED = "Generated by `mise run ci:generate-workflow`. Do not edit directly."
PINS = catalog(ROOT)
SCCACHE_ENVIRONMENT = "${{ github.event_name == 'push' && 'sccache' || '' }}"
RETENTION = "${{ github.event_name == 'pull_request' && 1 || 30 }}"
# A closed pull request run uses the PR's frozen last merge commit, so an old
# workflow can still start. Skip every job rather than plan on stale code.
# Current triggers fire only on open PRs. Keep the guard anyway.
OPEN = "github.event.pull_request.state != 'closed'"

KOTLIN_SNAPSHOT_VERSION = "0.1.0-SNAPSHOT"


def action(reference: str, inputs: dict | None = None, **fields) -> dict:
    pin = PINS[reference]
    step = CommentedMap({**fields, "uses": f"{pin.action}@{pin.sha}"})
    step.yaml_add_eol_comment(pin.version, "uses", column=0)
    if inputs:
        step["with"] = inputs
    return step


def checkout(runs_on: str, **inputs) -> dict:
    # Blacksmith's checkout clones from a mirror next to its runners.
    name = (
        "useblacksmith/checkout"
        if runs_on.startswith("blacksmith-")
        else "actions/checkout"
    )
    return action(
        name, {"persist-credentials": False, **inputs}, name="Check out repository"
    )


def run(command: str, **fields) -> dict:
    return {
        **fields,
        "run": LiteralScalarString(command) if "\n" in command else command,
    }


def setup(
    runs_on: str,
    target: str | None = None,
    *,
    zig=False,
    gradle=True,
    save_toolchains=False,
    fetch_tags=False,
) -> list[dict]:
    inputs = {
        "sccache-access-key-id": "${{ secrets.R2_SCCACHE_ACCESS_KEY_ID }}",
        "sccache-secret-access-key": "${{ secrets.R2_SCCACHE_SECRET_ACCESS_KEY }}",
    }
    if target:
        inputs["target"] = target
    if zig:
        inputs["zig"] = True
    if not gradle:
        inputs["gradle"] = False
    if save_toolchains:
        inputs["save-toolchains"] = True
    checkout_inputs = {"fetch-tags": True} if fetch_tags else {}
    return [
        checkout(runs_on, **checkout_inputs),
        {
            "name": "Set up CI dependencies",
            "uses": "./.github/actions/setup-ci-deps",
            "id": "setup",
            "with": inputs,
        },
    ]


def target_job(row: dict) -> dict:
    preset = row["preset"]
    steps = setup(
        row["runner"],
        preset,
        zig=row["zig"],
        gradle=row["gradle"],
        save_toolchains=row["save_toolchains"],
    )
    # Steps that fetch dependencies or boot a device carry the names that
    # ci/retry.py treats as infrastructure.
    if row["swift"]:
        steps.append(
            run(
                "mise run //bindings/swift:resolve",
                name="Resolve Swift packages",
                id="resolve",
            )
        )
    build, *checks = row["native_commands"]
    steps.append(run(build, id="build"))
    prerequisites = ["build"]
    if row["boot"]:
        name, command = row["boot"]
        steps.append(run(command, name=name, id="boot"))
        prerequisites.append("boot")
    suites: list[str] = []

    def guard() -> str:
        # A suite runs even after an earlier suite failed, so one run reports
        # every failed suite, but only when its build and device succeeded.
        # Each prerequisite runs only after the ones before it succeeded, so
        # the last one stands for them all.
        return (
            f"${{{{ !cancelled() && steps.{prerequisites[-1]}.outcome == 'success' }}}}"
        )

    def add_suite(command: str, env: dict[str, str] | None = None) -> None:
        suites.append(f"suite-{len(suites) + 1}")
        env = {**(env or {}), **row["environment"].get(command, {})}
        fields = {"env": env} if env else {}
        # Lavapipe presents Win32 surfaces through GDI, which needs the VM's
        # interactive desktop. WGL and the binding suites run in service session 0.
        if preset == "windows-x64-vulkan" and command == f"mise run test {preset}":
            command = (
                "./ci/with-windows-console.ps1 "
                f"-Command @('mise', 'run', 'test', '{preset}')"
            )
            fields.update(
                {
                    "name": "Run native tests in the Windows desktop session",
                    "shell": "pwsh",
                    "timeout-minutes": 15,
                }
            )
        steps.append(run(command, id=suites[-1], **{"if": guard()}, **fields))

    for command in checks:
        add_suite(command)
    if row["package"]:
        for step_id, name, command in (
            ("archive", "Archive native artifact", f"mise run archive-native {preset}"),
            (
                "install",
                "Install packaged native artifact",
                (
                    f"mise run install-native-package {preset} "
                    f"build/packages/native/dist/maplibre-native-c-{preset}.tar.gz"
                ),
            ),
        ):
            steps.append(run(command, name=name, id=step_id, **{"if": guard()}))
            prerequisites.append(step_id)
        for command in row["consumer_commands"]:
            add_suite(command, {"MISE_TASK_SKIP": "//:build"})
    # A failed job must not claim the immutable shared Zig cache with a partial
    # set of packages. Only rows covering every Zig project can save it.
    if row["zig"]:
        steps.append(
            action(
                "actions/cache/save",
                {
                    "path": LiteralScalarString(
                        "~/.cache/zig/p\n~/AppData/Local/zig/p\n"
                    ),
                    "key": "${{ steps.setup.outputs.zig-cache-key }}",
                },
                name="Save Zig packages",
                **{"if": "steps.setup.outputs.zig-cache-hit != 'true'"},
            )
        )
    if row["package"]:
        steps.append(
            action(
                "actions/upload-artifact",
                {
                    "name": f"native-package-{preset}-${{{{ github.sha }}}}",
                    "path": f"build/packages/native/dist/maplibre-native-c-{preset}.tar.gz",
                    "if-no-files-found": "error",
                    "retention-days": RETENTION,
                },
                name="Upload native artifact",
            )
        )
    # The npm release publishes the addon that the TypeScript suite built
    # against the packaged native artifact and tested, for each preset that
    # bindings/typescript/scripts/pack.ts packs.
    if preset.startswith(("linux-gnu-", "macos-", "emscripten-")) and (
        f"mise run //bindings/typescript:test {preset}"
        in row.get("consumer_commands", [])
    ):
        steps.append(
            action(
                "actions/upload-artifact",
                {
                    "name": f"typescript-addon-{preset}-${{{{ github.sha }}}}",
                    "path": f"bindings/typescript/native/build/{preset}/install",
                    "if-no-files-found": "error",
                    "retention-days": RETENTION,
                },
                name="Upload TypeScript addon",
            )
        )
    # The OHPM release packs the addon that each OpenHarmony job built against
    # the packaged native artifact. The npm release downloads every
    # typescript-addon artifact, so these take another prefix.
    if preset.startswith("ohos-") and any(
        f"mise run //bindings/typescript:{action_name} {preset}"
        in row.get("consumer_commands", [])
        for action_name in ("build", "test")
    ):
        steps.append(
            action(
                "actions/upload-artifact",
                {
                    "name": f"arkts-addon-{preset}-${{{{ github.sha }}}}",
                    "path": f"bindings/typescript/native/build/{preset}/install",
                    "if-no-files-found": "error",
                    "retention-days": RETENTION,
                },
                name="Upload ArkTS addon",
            )
        )
    if suites:
        # A failed suite already fails the job. This step collects the verdict
        # at the end of the log, after the suites that kept running.
        steps.append(
            run(
                "exit 1",
                name="Fail if any suite failed",
                shell="bash",
                **{
                    "if": "${{ !cancelled() && ("
                    + " || ".join(
                        f"steps.{suite}.outcome == 'failure'" for suite in suites
                    )
                    + ") }}"
                },
            )
        )
    return {
        "name": job_name(f"target-{preset}"),
        "runs-on": row["runner"],
        "timeout-minutes": 120,
        "environment": SCCACHE_ENVIRONMENT,
        "steps": steps,
    }


def hygiene_job() -> dict:
    commands = [
        run("mise run ci:generate-workflow --check"),
        run("mise run ci:test"),
        # A generator probe whose toolchain is missing fails here instead of
        # skipping.
        run(
            "mise run bindings:test-generator",
            env={"MLN_BINDGEN_REQUIRE_TOOLCHAINS": "1"},
        ),
        run("mise run bindings:generate --require-complete"),
        run("dprint output-resolved-config > /dev/null"),
        run("mise run fix"),
    ]
    return {
        "name": job_name(HYGIENE),
        "runs-on": LINUX_RUNNER,
        "timeout-minutes": 30,
        "environment": SCCACHE_ENVIRONMENT,
        "steps": [
            *setup(LINUX_RUNNER, gradle=False),
            *commands,
            run(
                "git update-index -q --refresh\n"
                "git diff --exit-code -- . ':(exclude)mise*.lock'\n"
                "git diff --cached --exit-code -- . ':(exclude)mise*.lock'\n"
                'untracked="$(git ls-files --others --exclude-standard)"\n'
                'test -z "$untracked" || { echo "$untracked"; exit 1; }\n',
                name="Check generated and formatted files",
            ),
        ],
    }


def docs_job() -> dict:
    versions = (ROOT / "gradle/libs.versions.toml").read_text()
    match = re.search(r'^android-compileSdk = "(\d+)"\s*$', versions, re.MULTILINE)
    if match is None:
        raise ValueError("android-compileSdk missing from gradle/libs.versions.toml")
    # Dokka configures the Android target and requires its SDK platform.
    return {
        "name": job_name("docs"),
        "runs-on": LINUX_RUNNER,
        "timeout-minutes": 60,
        "environment": SCCACHE_ENVIRONMENT,
        "steps": [
            # The pages quote the latest release versions from the release tags.
            *setup(LINUX_RUNNER, fetch_tags=True),
            action(
                "android-actions/setup-android",
                {
                    "packages": f"platform-tools platforms;android-{match[1]}",
                },
            ),
            run("mise run //docs:build"),
        ],
    }


def support_issue_job() -> dict:
    # The tracking issue follows main, while the site it summarizes follows
    # snapshot deploys. Only a push to main may write the issue.
    return {
        "name": "support issue",
        "runs-on": SMALL_RUNNER,
        "timeout-minutes": 10,
        "if": "github.event_name == 'push'",
        "permissions": {"contents": "read", "issues": "write"},
        "concurrency": {"group": "support-issue", "cancel-in-progress": False},
        "steps": [
            checkout(SMALL_RUNNER),
            action("jdx/mise-action", {"cache": False, "install_args": "python"}),
            run(
                "set -euo pipefail\n\n"
                "mise exec -- python docs/scripts/generate-support-matrix.py\n"
                "mise exec -- python docs/scripts/render-support-issue.py "
                '> "$RUNNER_TEMP/support-issue.md"\n'
                "issue=\"$(jq -r '.issue' docs/src/generated/support-matrix.json)\"\n"
                'gh issue edit "$issue" --body-file "$RUNNER_TEMP/support-issue.md"\n',
                name="Rewrite the support issue body",
                env={"GH_TOKEN": "${{ github.token }}"},
            ),
        ],
    }


def android_multi_job(needs: list[str]) -> dict:
    return {
        "name": job_name("android-multi"),
        "runs-on": LINUX_RUNNER,
        "timeout-minutes": 30,
        "environment": SCCACHE_ENVIRONMENT,
        "needs": needs,
        "steps": [
            *setup(LINUX_RUNNER, "android-multi"),
            action(
                "actions/download-artifact",
                {
                    "pattern": "native-package-android-*-${{ github.sha }}",
                    "path": "build/packages/native/android-multi-input",
                },
                name="Download Android native artifacts",
            ),
            run(
                "mise run //:kotlin:verify-android-multi-abi build/packages/native/android-multi-input",
            ),
        ],
    }


def apple_xcframework_job(needs: list[str]) -> dict:
    # The artifact is what the native package publish uploads.
    return {
        "name": job_name("apple-xcframework"),
        "runs-on": runner("macos-arm64-metal"),
        "timeout-minutes": 30,
        "environment": SCCACHE_ENVIRONMENT,
        "needs": needs,
        "steps": [
            *setup(runner("macos-arm64-metal"), "apple-xcframework", gradle=False),
            action(
                "actions/download-artifact",
                {
                    "pattern": "native-package-*-metal-${{ github.sha }}",
                    "path": "build/packages/native/xcframework-input",
                },
                name="Download Apple Metal native artifacts",
            ),
            run("mise run package-xcframework build/packages/native/xcframework-input"),
            action(
                "actions/upload-artifact",
                {
                    "name": "native-xcframework-${{ github.sha }}",
                    "path": "build/packages/native/dist/MaplibreNativeC.xcframework.zip",
                    "if-no-files-found": "error",
                    "retention-days": RETENTION,
                },
                name="Upload XCFramework",
            ),
        ],
    }


def kotlin_maven_job(needs: list[str]) -> dict:
    # Every run stages at the snapshot version, because snapshot publication
    # reuses the verified repository of a run on main.
    return {
        "name": job_name("kotlin-maven"),
        "permissions": {"actions": "read", "contents": "read"},
        "needs": needs,
        "uses": "./.github/workflows/_kotlin-maven.yml",
        "with": {
            "publish": False,
            "run_id": "${{ github.run_id }}",
            "sha": "${{ github.sha }}",
            "version": KOTLIN_SNAPSHOT_VERSION,
        },
    }


def plan_job() -> dict:
    # The action reports every unit on anything but a ready plan, and it never
    # fails the job. The job timeout leaves room for its own 600 second wait.
    return {
        "runs-on": SMALL_RUNNER,
        "timeout-minutes": 15,
        "if": OPEN,
        "outputs": {
            "all": "${{ steps.plan.outputs.all }}",
            "units": "${{ steps.plan.outputs.units }}",
        },
        "steps": [
            action("sargunv/rubberstamp/actions/plan", name="Plan coverage", id="plan")
        ],
    }


def gate(units: list[str]) -> str:
    """Run a job when the plan runs every unit or any of these units."""
    return " || ".join(
        [
            "fromJSON(needs.plan.outputs.all)",
            *(
                f"contains(fromJSON(needs.plan.outputs.units), '{unit}')"
                for unit in units
            ),
        ]
    )


def ci_workflow(source: dict, presets: dict) -> dict:
    rows = target_rows(source, presets)
    needs = dependencies(source, presets)
    running = job_units(source, presets)
    jobs = {"docs": docs_job()}
    jobs.update({f"target-{row['preset']}": target_job(row) for row in rows})
    jobs["android-multi"] = android_multi_job(needs["android-multi"])
    jobs["apple-xcframework"] = apple_xcframework_job(needs["apple-xcframework"])
    jobs["kotlin-maven"] = kotlin_maven_job(needs["kotlin-maven"])
    for name, job in jobs.items():
        job["needs"] = ["plan", *job.get("needs", [])]
        job["if"] = gate(running[name])
    # Hygiene always runs, without waiting for the plan.
    jobs = {HYGIENE: {**hygiene_job(), "if": OPEN}, **jobs}
    # A skipped job passes a required check, so a failed plan must fail this one.
    required = {
        "name": "ci-required",
        "runs-on": SMALL_RUNNER,
        "timeout-minutes": 5,
        "if": f"always() && {OPEN}",
        "needs": ["plan", *jobs],
        "steps": [
            run(
                'test "$PLAN" = success &&\n'
                'jq -e -n --argjson results "$RESULTS" '
                '\'all($results[]; .result == "success" or .result == "skipped")\'\n',
                name="Require every planned job",
                env={
                    "PLAN": "${{ needs.plan.result }}",
                    "RESULTS": "${{ toJSON(needs) }}",
                },
            )
        ],
    }
    return {
        "name": "CI",
        "on": {
            "push": {"branches": ["main"]},
            "workflow_dispatch": None,
            "pull_request": {"types": ["opened", "synchronize", "reopened"]},
        },
        "permissions": {"contents": "read"},
        # A newer push to main cancels the run it supersedes. A re-run, such as
        # the one a release starts for its cancelled commit, gets a group of
        # its own so that neither run cancels the other.
        "concurrency": {
            "group": "${{ github.workflow }}-${{ github.event.pull_request.number"
            " || (github.event_name == 'push' && github.run_attempt == '1' && github.ref)"
            " || format('{0}-{1}', github.run_id, github.run_attempt) }}",
            "cancel-in-progress": "${{ github.event.action == 'synchronize'"
            " || github.event_name == 'push' }}",
        },
        "jobs": {
            "plan": plan_job(),
            **jobs,
            "required": required,
            "support-issue": support_issue_job(),
        },
    }


def retry_workflow() -> dict:
    # workflow_run gets a write token. Its checkout must stay on the trusted
    # default-branch commit, never the PR that triggered the failed run.
    trusted_checkout = checkout(SMALL_RUNNER, ref="${{ github.sha }}")
    return {
        "name": "CI retry",
        "on": {
            "workflow_run": {
                "workflows": ["CI"],
                "types": ["completed"],
            }
        },
        "permissions": {"contents": "read", "actions": "write"},
        "concurrency": {
            "group": "${{ github.workflow }}-${{ github.event.workflow_run.id }}",
            "cancel-in-progress": False,
        },
        "jobs": {
            "retry": {
                "runs-on": SMALL_RUNNER,
                "timeout-minutes": 5,
                "if": "github.event.workflow_run.conclusion == 'failure' && github.event.workflow_run.run_attempt == 1",
                "steps": [
                    trusted_checkout,
                    run(
                        "python3 -m ci.retry",
                        name="Retry failed jobs and their dependents",
                        env={
                            "GH_TOKEN": "${{ github.token }}",
                            "CI_RUN_ID": "${{ github.event.workflow_run.id }}",
                        },
                    ),
                ],
            }
        },
    }


def workflows(source: dict, presets: dict) -> dict[str, dict]:
    return {
        # A closed pull request runs the workflow file in its frozen merge ref,
        # so the old ci.yml path stays disabled in the repository settings.
        "ci-coverage.yml": ci_workflow(source, presets),
        "ci-retry.yml": retry_workflow(),
    }


def serialize(workflow: dict) -> str:
    yaml = YAML()
    yaml.indent(mapping=2, sequence=4, offset=2)
    yaml.width = 4096
    document = CommentedMap(workflow)
    document.yaml_set_start_comment(GENERATED)
    stream = io.StringIO()
    yaml.dump(document, stream)
    return stream.getvalue()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = workflows(*load_configuration(ROOT))
    directory = ROOT / ".github/workflows"
    valid = True
    # A generated workflow that the generator no longer produces is stale.
    for path in sorted(directory.glob("*.yml")):
        if path.name not in outputs and path.read_text().startswith(f"# {GENERATED}"):
            if args.check:
                valid = False
                print(f"{path} is no longer generated", file=sys.stderr)
            else:
                path.unlink()
    for name, workflow in outputs.items():
        path = directory / name
        expected = serialize(workflow)
        actual = path.read_text() if path.exists() else ""
        if args.check:
            if actual != expected:
                valid = False
                sys.stderr.writelines(
                    difflib.unified_diff(
                        actual.splitlines(keepends=True),
                        expected.splitlines(keepends=True),
                        fromfile=str(path),
                        tofile=f"{path} (generated)",
                    )
                )
        else:
            path.write_text(expected)
    return 0 if valid else 1


if __name__ == "__main__":
    raise SystemExit(main())
