"""Aggregate the monorepo's project tools for the devcontainer image.

mise has no config include, so the devcontainer's tool list is generated from
the project configs. `mise install --monorepo` is not a substitute: `mise oci
build` packages only the config it runs on and that config's parents.
"""

from __future__ import annotations

import pathlib
import re
import tomllib

MARKER_BEGIN = "# BEGIN generated tools"
MARKER_END = "# END generated tools"

HEADER = """\
# The published devcontainer is the aggregate environment: every tool used by a
# binding, example, or docs project, while normal root installs stay lean.
# Generated by `mise run ci:generate-devcontainer-tools`. Do not edit directly.\
"""

TOOLS_PATTERN = re.compile(r"^\[tools\]\n(.*?)(?=^\[|\Z)", re.MULTILINE | re.DOTALL)


def project_configs(root: pathlib.Path) -> list[pathlib.Path]:
    """Every monorepo project config except the aggregate itself."""
    with (root / "mise.toml").open("rb") as file:
        config_roots = tomllib.load(file)["monorepo"]["config_roots"]
    paths = []
    for pattern in config_roots:
        if pattern == ".devcontainer":
            continue
        for directory in sorted(root.glob(pattern)):
            config = directory / "mise.toml"
            if config.is_file():
                paths.append(config)
    return paths


def parse_tool_assignments(body: str) -> dict[str, str]:
    """Map each `[tools]` key to its full assignment, including wrapped values.

    Toml 0.9 wraps inline arrays across lines. Splitting on newlines would treat
    those continuation lines as keys and emit invalid aggregate TOML.
    """
    assignments: dict[str, str] = {}
    i = 0
    n = len(body)
    while i < n:
        while i < n and body[i] in " \t\r\n":
            i += 1
        if i >= n:
            break
        if body[i] == "#":
            while i < n and body[i] != "\n":
                i += 1
            continue
        begin = i
        while i < n and body[i] != "=":
            i += 1
        if i >= n:
            break
        key = body[begin:i].strip().strip('"')
        i += 1
        depth_brace = 0
        depth_bracket = 0
        quote = None
        escape = False
        while i < n:
            ch = body[i]
            if quote is not None:
                if escape:
                    escape = False
                elif ch == "\\":
                    escape = True
                elif ch == quote:
                    quote = None
                i += 1
                continue
            if ch in "\"'":
                quote = ch
            elif ch == "{":
                depth_brace += 1
            elif ch == "}":
                depth_brace -= 1
            elif ch == "[":
                depth_bracket += 1
            elif ch == "]":
                depth_bracket -= 1
            elif ch == "\n" and depth_brace == 0 and depth_bracket == 0:
                break
            i += 1
        assignments[key] = body[begin:i].strip()
        if i < n and body[i] == "\n":
            i += 1
    return assignments


def tool_lines(config: pathlib.Path) -> dict[str, str]:
    """Map each tool in a config's `[tools]` table to its source assignment.

    Reusing the source text keeps the aggregate formatted exactly like the
    project configs, which the formatter has already normalized.
    """
    match = TOOLS_PATTERN.search(config.read_text())
    if not match:
        return {}
    return parse_tool_assignments(match.group(1))


def aggregate(root: pathlib.Path) -> str:
    tools: dict[str, str] = {}
    sources: dict[str, pathlib.Path] = {}
    for config in project_configs(root):
        for tool, line in tool_lines(config).items():
            previous = tools.get(tool)
            if previous is not None and previous != line:
                raise SystemExit(
                    f"error: {tool} is declared differently in "
                    f"{sources[tool].relative_to(root)} and "
                    f"{config.relative_to(root)}:\n  {previous}\n  {line}"
                )
            tools[tool] = line
            sources.setdefault(tool, config)
    body = "\n".join(tools[tool] for tool in sorted(tools))
    return f"{MARKER_BEGIN}\n{HEADER}\n[tools]\n{body}\n{MARKER_END}"


def render(root: pathlib.Path) -> str:
    """The devcontainer config with its generated tools block replaced."""
    output = root / ".devcontainer" / "mise.toml"
    text = output.read_text()
    pattern = re.compile(
        rf"{re.escape(MARKER_BEGIN)}\n.*?{re.escape(MARKER_END)}", re.DOTALL
    )
    if not pattern.search(text):
        raise SystemExit(
            f"error: {output.relative_to(root)} is missing the "
            f"`{MARKER_BEGIN}` / `{MARKER_END}` markers"
        )
    return pattern.sub(lambda _: aggregate(root), text)
